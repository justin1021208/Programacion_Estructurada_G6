#Leer 2 numeros y calcular: la suma, resta, multiplicacion, division y comprobar si el primero es multiplo del segundo

number1 = int(input("Ingresa un numero: "))
number2 = int(input("Ingresa otro numero: "))

print(f"{number1} + {number2} = {number1 + number2 }")
print(f"{number1} - {number2} = {number1 - number2 }")
print(f"{number1} * {number2} = {number1 * number2 }")
print(f"{number1} / {number2} = {number1 / number2 }")
print(f"{number1} % {number2} = {number1 % number2 }")

